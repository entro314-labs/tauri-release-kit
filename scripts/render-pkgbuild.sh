#!/usr/bin/env bash
# Render the PKGBUILD and .install scriptlet that repack a release's .deb files into an Arch
# package. One renderer for both Arch channels, so they cannot drift apart:
#   aur.yml       -> a `-bin` PKGBUILD whose sources are the release's download URLs
#   arch-repo.yml -> a PKGBUILD over the already-downloaded .deb files, built with makepkg
#
# Usage: render-pkgbuild.sh <out dir> <sources env> [base url]
#
#   <out dir>      receives PKGBUILD and <pkgname>.install
#   <sources env>  shell file with ASSET_<arch>=<release asset name> and SHA_<arch>=<sha256>
#                  for every architecture in FOUND_ARCHES
#   base url       release download URL (https://github.com/<repo>/releases/download/<tag>).
#                  Set: sources are `<pkgname>-<pkgver>-<arch>.deb::<base url>/<asset>`.
#                  Empty: sources are the local file `<pkgname>-<pkgver>-<arch>.deb`, which the
#                  caller places next to the PKGBUILD before running makepkg.
#
# Package metadata comes from the environment: PKGNAME PKGVER PKGREL PKGDESC URL LICENSE
# (comma-separated) DEPENDS PROVIDES CONFLICTS (space-separated) MAINTAINER FOUND_ARCHES.
set -euo pipefail
out="$1"; sources="$2"; base="${3:-}"
: "${PKGNAME:?}" "${PKGVER:?}" "${PKGREL:?}" "${PKGDESC:?}" "${URL:?}" "${LICENSE:?}" "${DEPENDS:?}" "${FOUND_ARCHES:?}"

# shellcheck disable=SC1090
. "$sources"
mkdir -p "$out"

quote_list() { for w in $1; do printf "'%s' " "$w"; done; }

{
  if [ -n "${MAINTAINER:-}" ]; then printf '# Maintainer: %s\n' "$MAINTAINER"; fi
  printf '# Generated by tauri-release-kit. Edits here are overwritten on the next release.\n\n'
  printf 'pkgname=%s\n' "$PKGNAME"
  printf 'pkgver=%s\n' "$PKGVER"
  printf 'pkgrel=%s\n' "$PKGREL"
  printf 'pkgdesc="%s"\n' "$PKGDESC"
  printf 'arch=(%s)\n' "$(quote_list "$FOUND_ARCHES")"
  printf 'url="%s"\n' "$URL"
  printf 'license=(%s)\n' "$(quote_list "$(printf '%s' "$LICENSE" | tr ',' ' ')")"
  printf 'depends=(%s)\n' "$(quote_list "$DEPENDS")"
  if [ -n "${PROVIDES:-}" ];  then printf 'provides=(%s)\n'  "$(quote_list "$PROVIDES")"; fi
  if [ -n "${CONFLICTS:-}" ]; then printf 'conflicts=(%s)\n' "$(quote_list "$CONFLICTS")"; fi
  # !strip: the binary is already stripped and re-stripping a release build wastes time (and
  # cannot work on an aarch64 binary from an x86_64 builder); !debug: there is no source to
  # attach debug symbols to, and without this makepkg tries to build an empty -debug package
  # and fails.
  printf "options=('!strip' '!debug')\n"
  printf 'install=%s.install\n' "$PKGNAME"
  for arch in $FOUND_ARCHES; do
    asset_var="ASSET_${arch}"; sha_var="SHA_${arch}"
    asset="${!asset_var:?no ASSET_${arch} in $sources}"; sha="${!sha_var:?no SHA_${arch} in $sources}"
    local_name="${PKGNAME}-${PKGVER}-${arch}.deb"
    if [ -n "$base" ]; then
      # <name>::<url> renames the download so two versions never collide in makepkg's shared
      # source cache.
      printf 'source_%s=("%s::%s/%s")\n' "$arch" "$local_name" "${base%/}" "$asset"
    else
      printf 'source_%s=("%s")\n' "$arch" "$local_name"
    fi
    printf "sha256sums_%s=('%s')\n" "$arch" "$sha"
  done
  printf '\npackage() {\n'
  # Literal PKGBUILD source: $pkgdir must reach makepkg unexpanded.
  # shellcheck disable=SC2016
  printf '  # The .deb layout maps 1:1 onto $pkgdir; nothing needs rewriting.\n'
  # shellcheck disable=SC2016
  printf '  tar -xf data.tar.* -C "${pkgdir}"\n'
  printf '}\n'
} > "$out/PKGBUILD"

# The .install scriptlet refreshes the icon and desktop-entry caches. Without it the app installs
# but does not appear in the launcher until something else happens to refresh them.
cat > "$out/${PKGNAME}.install" <<'INSTALL'
post_install() {
  gtk-update-icon-cache -q -t -f usr/share/icons/hicolor
  update-desktop-database -q
}

post_upgrade() {
  post_install
}

post_remove() {
  post_install
}
INSTALL
